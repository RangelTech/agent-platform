type Lang = 'pt' | 'en'
type Page = 'privacidade' | 'termos' | 'exclusao'

const CONTACT_EMAIL = 'privacidade@rangeltech.net'

function Toggle({ lang, onChange }: { lang: Lang; onChange: (l: Lang) => void }) {
  return (
    <div className="mb-8 flex justify-end gap-2 text-sm">
      <button
        onClick={() => onChange('pt')}
        className={`rounded-full px-3 py-1 ${lang === 'pt' ? 'bg-[var(--brand)] text-white' : 'border border-[var(--border)] text-[var(--text-muted)]'}`}
      >
        Português
      </button>
      <button
        onClick={() => onChange('en')}
        className={`rounded-full px-3 py-1 ${lang === 'en' ? 'bg-[var(--brand)] text-white' : 'border border-[var(--border)] text-[var(--text-muted)]'}`}
      >
        English
      </button>
    </div>
  )
}

function Shell({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div className="mx-auto min-h-screen max-w-3xl px-6 py-12 text-[var(--text)]">
      <a href="/" className="text-sm text-[var(--text-muted)] hover:underline">
        ← Agente IA — Rangel Tech
      </a>
      <h1 className="mt-4 mb-2 text-3xl font-semibold">{title}</h1>
      <p className="mb-8 text-sm text-[var(--text-faint)]">Rangel Tech · Última atualização: 17/08/2026</p>
      <div className="space-y-6 leading-7 text-[var(--text-muted)]">{children}</div>
    </div>
  )
}

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <section>
      <h2 className="mb-2 text-lg font-medium text-[var(--text)]">{title}</h2>
      <div className="space-y-2">{children}</div>
    </section>
  )
}

