function Exclusao({ lang }: { lang: Lang }) {
  if (lang === 'en') {
    return (
      <Shell title="Data Deletion">
        <Section title="How to request deletion">
          <p>
            End users or clients may request deletion of their data by emailing{' '}
            <a className="underline" href={`mailto:${CONTACT_EMAIL}`}>{CONTACT_EMAIL}</a> from the
            address associated with the account, or via the messaging channel itself by requesting
            deletion, in which case the client's support team will forward the request to us.
          </p>
        </Section>
        <Section title="What gets deleted">
          <p>
            Conversation history, contact data and any AI-extracted memory tied to the requester's
            identifier on the connected channel. We will confirm completion by email within a reasonable
            timeframe.
          </p>
        </Section>
        <Section title="Revoking the app instead">
          <p>
            To immediately stop new data collection without waiting for a deletion request to be
            processed, disconnect/revoke the app's access in your Instagram/Facebook/WhatsApp account
            settings at any time.
          </p>
        </Section>
      </Shell>
    )
  }
  return (
    <Shell title="Exclusão de Dados">
      <Section title="Como pedir exclusão">
        <p>
          Usuários finais ou clientes podem pedir a exclusão dos seus dados enviando e-mail para{' '}
          <a className="underline" href={`mailto:${CONTACT_EMAIL}`}>{CONTACT_EMAIL}</a> a partir do
          endereço associado à conta, ou pelo próprio canal de mensageria pedindo a exclusão — nesse caso
          a equipe de atendimento do cliente encaminha o pedido para nós.
        </p>
      </Section>
      <Section title="O que é excluído">
        <p>
          Histórico de conversa, dado de contato e qualquer memória extraída pela IA vinculada ao
          identificador de quem pediu, no canal conectado. Confirmamos a conclusão por e-mail em prazo
          razoável.
        </p>
      </Section>
      <Section title="Revogar o app em vez de esperar">
        <p>
          Para parar imediatamente a coleta de novos dados sem esperar o processamento do pedido de
          exclusão, desconecte/revogue o acesso do app nas configurações da sua conta Instagram/Facebook/
          WhatsApp a qualquer momento.
        </p>
      </Section>
    </Shell>
  )
}

export default function Legal({ page }: { page: Page }) {
  const [lang, setLang] = useState<Lang>('pt')
  return (
    <div className="min-h-screen bg-[var(--bg)]">
      <div className="mx-auto max-w-3xl px-6 pt-6">
        <Toggle lang={lang} onChange={setLang} />
      </div>
      {page === 'privacidade' && <Privacidade lang={lang} />}
      {page === 'termos' && <Termos lang={lang} />}
      {page === 'exclusao' && <Exclusao lang={lang} />}
    </div>
  )
}
